function phaseEnthalpyRecord(phase: string, context?: AntimonyHeatEnthalpyContext) {
  const key = normalizeMetcalPhaseFormula(phase) || phase
  return (context ? ANTIMONY_PRODUCT_PHASE_ENTHALPY_KJ_MOL[context]?.[phase] : undefined) ??
    (context ? ANTIMONY_PRODUCT_PHASE_ENTHALPY_KJ_MOL[context]?.[key] : undefined) ??
    ANTIMONY_PHASE_ENTHALPY_KJ_MOL[phase] ??
    ANTIMONY_PHASE_ENTHALPY_KJ_MOL[key]
}

export function antimonyEnthalpy25KJmol(phase: string, context?: AntimonyHeatEnthalpyContext) {
  return phaseEnthalpyRecord(phase, context)?.h25 ?? ANTIMONY_INPUT_STANDARD_ENTHALPY_KJ_MOL[phase] ?? null
}

